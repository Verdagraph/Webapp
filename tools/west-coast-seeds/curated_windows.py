"""Frost-anchored sowing windows read from each crop's timing text, keyed by crop name.

Only what the text states is recorded: a number of weeks before or after a frost date, or "after the
last frost" as day 0. Seasonal wording with no frost date ("early spring", "late May") is left out.
A window is (open, close) in days from the frost date, with close None when the text gives no end.
Windows are {method: {frost: (open, close)}} for the methods directSeed, indoorStart and
transplantOut, and the frosts lastFrost and firstFrost. Where the text says to plant out "after the
last frost", the seeds are assumed to be started that many weeks before it.
"""
W = {}
def weeks(n):
    return round(n * 7)
def window(crop, **methods):
    W[crop] = {method: {frost: spec for frost, spec in frosts.items()} for method, frosts in methods.items()}

